function getBrand(model: string): string {
  const brands = ['HP', 'Lenovo', 'ASUS', 'Acer', 'Dell', 'MSI'];
  for (const brand of brands) {
    if (model.toUpperCase().startsWith(brand.toUpperCase())) return brand;
  }
  return 'Unknown';
}

function getImage(model: string): string {
  const brand = getBrand(model);
  if (model.includes('Victus') || model.includes('Victus')) return '/images/laptop-hp-victus.png';
  if (model.includes('Legion')) return '/images/laptop-lenovo-legion.png';
  if (model.includes('ROG')) return '/images/laptop-asus-rog.png';
  return brandImages[brand] || '/images/laptop-hp-pavilion.png';
}

function getCategory(model: string, _processor: string, graphics: string): string {
  const lower = `${model} ${graphics}`.toLowerCase();
  if (lower.includes('rtx') || lower.includes('gtx') || lower.includes('rx 6500') || lower.includes('rx 640')) {
    return 'Gaming';
  }
  if (lower.includes('i3') || lower.includes('ryzen 3') || lower.includes('ryzen 5 3450')) {
    return 'Budget';
  }
  if (lower.includes('probook') || lower.includes('latitude') || lower.includes('vostro')) {
    return 'Business';
  }
  return 'Gaming';
}

